        /// </para>
        /// <para>
        /// From: <see href="https://learn.microsoft.com/en-us/windows/console/getstdhandle"/>
        /// </para>
        /// </summary>
        /// <param name="nStdHandle">
        /// <para>
        /// The standard device. This parameter can be one of the following values.
        /// </para>
        /// <para>
        /// <list type="table">
        /// <listheader>
        /// <term>
        /// Value
        /// </term>
        /// <term>
        /// Meaning
        /// </term>
        /// </listheader>
        /// <item>
        /// <term>
        /// <see cref="STD_INPUT_HANDLE"/> <c>((DWORD)-10)</c>
        /// </term>
        /// <term>
        /// The standard input device. Initially, this is the console input buffer, <c>CONIN$</c>.
        /// </term>
        /// </item>
        /// <item>
        /// <term>
        /// <see cref="STD_OUTPUT_HANDLE"/> <c>((DWORD)-11)</c>
        /// </term>
        /// <term>
        /// The standard output device. Initially, this is the active console screen buffer, <c>CONOUT$</c>.
        /// </term>
        /// </item>
        /// <item>
        /// <term>
        /// <see cref="STD_ERROR_HANDLE"/> <c>((DWORD)-12)</c>
        /// </term>
        /// <term>
