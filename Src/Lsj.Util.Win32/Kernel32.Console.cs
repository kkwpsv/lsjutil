        /// </para>
        /// <para>
        ///  Tip
        /// </para>
        /// <para>
        /// It is not required to dispose of this handle with <see cref="CloseHandle"/> when done.
        /// See Remarks for more information.
        /// </para>
        /// <para>
        /// If the function fails, the return value is <see cref="INVALID_HANDLE_VALUE"/>.
        /// To get extended error information, call <see cref="GetLastError"/>.
        /// </para>
        /// <para>
        /// If an application does not have associated standard handles,
        /// such as a service running on an interactive desktop, and has not redirected them, the return value is <see cref="NULL"/>.
        /// </para>
        /// </returns>
        /// <remarks>
        /// <para>
        /// Handles returned by <see cref="GetStdHandle"/> can be used by applications that need to read from or write to the console.
        /// When a console is created, the standard input handle is a handle to the console's input buffer,
        /// and the standard output and standard error handles are handles of the console's active screen buffer.
        /// These handles can be used by the <see cref="ReadFile"/> and <see cref="WriteFile"/> functions,
        /// or by any of the console functions that access the console input buffer or a screen buffer
        /// (for example, the <see cref="ReadConsoleInput"/>, <see cref="WriteConsole"/>, or <see cref="GetConsoleScreenBufferInfo"/> functions).
        /// </para>
        /// <para>
        /// The standard handles of a process may be redirected by a call to <see cref="SetStdHandle"/>,
        /// in which case <see cref="GetStdHandle"/> returns the redirected handle.
        /// If the standard handles have been redirected, you can specify the <c>CONIN$</c> value
        /// in a call to the <see cref="CreateFile"/> function to get a handle to a console's input buffer.
        /// Similarly, you can specify the <c>CONOUT$</c> value to get a handle to a console's active screen buffer.
        /// </para>
        /// <para>
        /// The standard handles of a process on entry of the main method are dictated
        /// by the configuration of the <c>/SUBSYSTEM</c> flag passed to the linker when the application was built.
        /// Specifying <c>/SUBSYSTEM:CONSOLE</c> requests that the operating system fill the handles with a console session on startup,
        /// if the parent didn't already fill the standard handle table by inheritance.
        /// On the contrary, <c>/SUBSYSTEM:WINDOWS</c> implies that the application does not need a console
        /// and will likely not be making use of the standard handles.
        /// More information on handle inheritance can be found in the documentation for <see cref="STARTF_USESTDHANDLES"/>.
        /// </para>
        /// <para>
        /// Some applications operate outside the boundaries of their declared subsystem;
        /// for instance, a <c>/SUBSYSTEM:WINDOWS</c> application might check/use standard handles
        /// for logging or debugging purposes but operate normally with a graphical user interface.
        /// These applications will need to carefully probe the state of standard handles on startup
        /// and make use of <see cref="AttachConsole"/>, <see cref="AllocConsole"/>, and <see cref="FreeConsole"/> to add/remove a console if desired.
        /// </para>
        /// <para>
        /// Some applications may also vary their behavior on the type of inherited handle.
        /// Disambiguating the type between console, pipe, file, and others can be performed with <see cref="GetFileType"/>.
        /// </para>
        /// <para>
        /// Handle disposal
        /// </para>
        /// <para>
        /// It is not required to <see cref="CloseHandle"/> when done with the handle retrieved from <see cref="GetStdHandle"/>.
        /// The returned value is simply a copy of the value stored in the process table.
        /// The process itself is generally considered the owner of these handles and their lifetime.
        /// Each handle is placed in the table on creation depending on the inheritance
        /// and launch specifics of the <see cref="CreateProcess"/> call and will be freed when the process is destroyed.
        /// </para>
        /// <para>
        /// Manual manipulation of the lifetime of these handles may be desirable for an application
        /// intentionally trying to replace them or block other parts of the process from using them.
        /// As a <see cref="HANDLE"/> can be cached by running code, that code will not necessarily pick up changes made via <see cref="SetStdHandle"/>.
        /// Closing the handle explicitly via <see cref="CloseHandle"/> will close it process-wide
        /// and the next usage of any cached reference will encounter an error.
        /// </para>
        /// <para>
        /// Guidance for replacing a standard handle in the process table
        /// would be to get the existing <see cref="HANDLE"/> from the table with <see cref="GetStdHandle"/>,
        /// use <see cref="SetStdHandle"/> to place a new <see cref="HANDLE"/> in that is opened with <see cref="CreateFile"/>
        /// (or a similar function), then to close the retrieved handle.
        /// </para>
        /// <para>
        /// There is no validation of the values stored as handles in the process table
        /// by either the <see cref="GetStdHandle"/> or <see cref="SetStdHandle"/> functions.
        /// Validation is performed at the time of the actual read/write operation
        /// such as <see cref="ReadFile"/> or <see cref="WriteFile"/>.
        /// </para>
        /// <para>
        /// Attach/detach behavior
        /// </para>
        /// <para>
        /// When attaching to a new console, standard handles are always replaced with console handles
        /// unless <see cref="STARTF_USESTDHANDLES"/> was specified during process creation.
        /// </para>
        /// <para>
        /// If the existing value of the standard handle is <see cref="NULL"/>,
        /// or the existing value of the standard handle looks like a console pseudohandle, the handle is replaced with a console handle.
        /// </para>
        /// <para>
        /// When a parent uses both <see cref="CREATE_NEW_CONSOLE"/> and <see cref="STARTF_USESTDHANDLES"/> to create a console process,
        /// standard handles will not be replaced unless the existing value of the standard handle is <see cref="NULL"/> or a console pseudohandle.
        /// </para>
        /// <para>
        ///  Note
        /// </para>
        /// <para>
        /// Console processes must start with the standard handles filled or they will be filled automatically with appropriate handles to a new console.
        /// Graphical user interface (GUI) applications can be started without the standard handles and they will not be automatically filled.
        /// </para>
        /// </remarks>
        [WindowsVersionRequirement(WindowsVersion.WindowsNT40)]
        [DllImport("kernel32.dll", CharSet = CharSet.Unicode, EntryPoint = "GetStdHandle", ExactSpelling = true, SetLastError = true)]
        public static extern HANDLE GetStdHandle([In] DWORD nStdHandle);

