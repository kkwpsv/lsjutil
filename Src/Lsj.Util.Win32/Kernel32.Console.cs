        [DllImport("kernel32.dll", CharSet = CharSet.Unicode, EntryPoint = "ClosePseudoConsole", ExactSpelling = true, SetLastError = true)]
        public static extern void ClosePseudoConsole([In] HPCON hPC);

        /// <summary>
        /// <para>
        /// Important
        /// </para>
        /// <para>
