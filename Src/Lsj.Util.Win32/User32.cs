        /// <summary>
        /// <para>
        /// Sets an event hook function for a range of events.
        /// </para>
        /// <para>
        /// From: <see href="https://learn.microsoft.com/en-us/windows/win32/api/winuser/nf-winuser-setwineventhook"/>
        /// </para>
        /// </summary>
        /// <param name="eventMin">
        /// Specifies the event constant for the lowest event value in the range of events that are handled by the hook function.
        /// This parameter can be set to <see cref="EVENT_MIN"/> to indicate the lowest possible event value.
        /// </param>
        /// <param name="eventMax">
        /// Specifies the event constant for the highest event value in the range of events that are handled by the hook function.
        /// This parameter can be set to <see cref="EVENT_MAX"/> to indicate the highest possible event value.
        /// </param>
        /// <param name="hmodWinEventProc">
        /// Handle to the DLL that contains the hook function at <paramref name="pfnWinEventProc"/>,
        /// if the <see cref="WINEVENT_INCONTEXT"/> flag is specified in the <paramref name="dwFlags"/> parameter.
        /// If the hook function is not located in a DLL, or if the <see cref="WINEVENT_OUTOFCONTEXT"/> flag is specified,
        /// this parameter is <see cref="NULL"/>.
        /// </param>
        /// <param name="pfnWinEventProc">
        /// Pointer to the event hook function.
        /// For more information about this function, see WinEventProc.
        /// </param>
        /// <param name="idProcess">
        /// Specifies the ID of the process from which the hook function receives events.
        /// Specify zero (0) to receive events from all processes on the current desktop.
        /// </param>
        /// <param name="idThread">
        /// Specifies the ID of the thread from which the hook function receives events.
        /// If this parameter is zero, the hook function is associated with all existing threads on the current desktop.
        /// </param>
        /// <param name="dwFlags">
        /// Flag values that specify the location of the hook function and of the events to be skipped.
        /// The following flags are valid:
        /// <see cref="WINEVENT_INCONTEXT"/>, <see cref="WINEVENT_OUTOFCONTEXT"/>,
        /// <see cref="WINEVENT_SKIPOWNPROCESS"/>, <see cref="WINEVENT_SKIPOWNTHREAD"/>
        /// The following flag combinations are valid:
        /// <code>WINEVENT_INCONTEXT | WINEVENT_SKIPOWNPROCESS</code>
        /// <code>WINEVENT_INCONTEXT | WINEVENT_SKIPOWNTHREAD</code>
        /// <code>WINEVENT_OUTOFCONTEXT | WINEVENT_SKIPOWNPROCESS</code>
        /// <code>WINEVENT_OUTOFCONTEXT | WINEVENT_SKIPOWNTHREAD</code>
        /// Additionally, client applications can specify <see cref="WINEVENT_INCONTEXT"/>, or <see cref="WINEVENT_OUTOFCONTEXT"/> alone.
        /// See Remarks section for information on Windows Store app development.
        /// </param>
        /// <returns>
        /// If successful, returns an <see cref="HWINEVENTHOOK"/> value that identifies this event hook instance.
        /// Applications save this return value to use it with the <see cref="UnhookWinEvent"/> function.
        /// If unsuccessful, returns zero.
        /// </returns>
        /// <remarks>
        /// This function allows clients to specify which processes and threads they are interested in.
        /// If the <paramref name="idProcess"/> parameter is nonzero and <paramref name="idThread"/> is zero,
        /// the hook function receives the specified events from all threads in that process.
        /// If the <paramref name="idProcess"/> parameter is zero and <paramref name="idThread"/> is nonzero,
        /// the hook function receives the specified events only from the thread specified by <paramref name="idThread"/>.
        /// If both are zero, the hook function receives the specified events from all threads and processes.
        /// Clients can call <see cref="SetWinEventHook"/> multiple times if they want to register additional hook functions or listen for additional events.
        /// The client thread that calls <see cref="SetWinEventHook"/> must have a message loop in order to receive events.
        /// When you use <see cref="SetWinEventHook"/> to set a callback in managed code,
        /// you should use the <see cref="GCHandle"/> structure to avoid exceptions.
        /// This tells the garbage collector not to move the callback.
        /// For out-of-context events, the event is delivered on the same thread that called <see cref="SetWinEventHook"/>.
        /// In some situations, even if you request <see cref="WINEVENT_INCONTEXT"/> events, the events will still be delivered out-of-context.
        /// These scenarios include events from console windows and events from processes
        /// that have a different bit-depth (64 bit versus 32 bits) than the caller.
        /// While a hook function processes an event, additional events may be triggered,
        /// which may cause the hook function to reenter before the processing for the original event is finished.
        /// The problem with reentrancy in hook functions is that events are completed out of sequence unless the hook function handles this situation.
        /// For more information, see Guarding Against Reentrancy.
        /// Windows Store app development If <paramref name="dwFlags"/> is <see cref="WINEVENT_INCONTEXT"/>
        /// AND (<paramref name="idProcess"/> = 0 | <paramref name="idThread"/> = 0),
        /// then window hook DLLs are not loaded in-process for the Windows Store app processes and the Windows Runtime broker process
        /// unless they are installed by UIAccess processes (accessibility tools).
        /// The notification is delivered on the installer's thread.
        /// This behavior is similar to what happens when there is an architecture mismatch between the hook DLL and the target application process,
        /// for example, when the hook DLL is 32-bit and the application process 64-bit.
        /// </remarks>
        [WindowsVersionRequirement(WindowsVersion.Windows2000)]
        [DllImport("user32.dll", CharSet = CharSet.Unicode, EntryPoint = "SetWinEventHook", ExactSpelling = true, SetLastError = true)]
        public static extern HWINEVENTHOOK SetWinEventHook([In] EventConstants eventMin, [In] EventConstants eventMax, [In] HMODULE hmodWinEventProc,
            [In] WINEVENTPROC pfnWinEventProc, [In] DWORD idProcess, [In] DWORD idThread, [In] SetWinEventHookFlags dwFlags);

